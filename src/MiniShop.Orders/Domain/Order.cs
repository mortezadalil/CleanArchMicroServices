// MiniShop.Orders — Domain/Order.cs
// ==================================================================================================
//
// WHAT THIS FILE IS
//   The domain model of the Orders service: the Order aggregate, its lines (OrderItem), the order
//   lifecycle as the customer sees it (OrderState) and an append-only audit trail (OrderAudit).
//
// WHERE IT SITS IN THE ARCHITECTURE
//   These classes are stored in orders.db through EF Core (Data/OrdersDbContext.cs). They are created
//   by the API (Api/OrdersEndpoints.cs) and changed ONLY by the saga (Saga/SagaRunner.cs). They are
//   never sent over the wire: other services learn about orders through message CONTRACTS
//   (contracts/Events.cs), which keeps the internal model free to change.
//
// NOTE ON TWO STATE FIELDS
//   An order has OrderState (here, customer-facing) and the saga has its own CurrentState
//   (Saga/OrderSagaState.cs, technical). They move together but are not the same thing: e.g. the saga
//   can be "WaitingForPaymentCancellation" while the customer simply sees "Compensating".
//
// Read next: Data/OrdersDbContext.cs (how these classes map to tables).
// ==================================================================================================

namespace MiniShop.Orders.Domain;

/// <summary>
/// Lifecycle of an order as the CUSTOMER sees it.
///   Pending → Reserving → AwaitingPayment → Confirmed
///                       ↘ Compensating → Rejected
///   Reserving → Rejected (out of stock)
///   Compensating → RequiresAttention (compensation could not be confirmed)
/// Stored as a string in the database (see OrdersDbContext) so the rows are readable.
/// </summary>
public enum OrderState
{
    /// <summary>Accepted by the API (202); OrderPlaced is in the outbox, nothing else happened yet.</summary>
    Pending,
    /// <summary>The saga asked Inventory to reserve stock and is waiting for the answer.</summary>
    Reserving,
    /// <summary>Stock is reserved; the saga asked Payments to charge the wallet.</summary>
    AwaitingPayment,
    /// <summary>Something failed after a reservation; the saga is undoing work (ReleaseStock / CancelPayment).</summary>
    Compensating,
    /// <summary>Terminal: stock reserved and money taken. Happy end (S01), or reconciled late payment (S13).</summary>
    Confirmed,
    /// <summary>Terminal: no stock (S02), or failure whose compensation Inventory CONFIRMED (S03, S10).</summary>
    Rejected,
    /// <summary>
    /// A compensation was never confirmed after several attempts (S12). We do NOT claim "Rejected",
    /// because stock may still be held; a human must look at it (retry-compensation endpoint).
    /// </summary>
    RequiresAttention,
}

/// <summary>The Orders aggregate. Prices are a SNAPSHOT of what the customer saw; Inventory re-validates them.</summary>
public sealed class Order
{
    /// <summary>Primary key, generated by the API. Also the saga's CorrelationId and every message's CorrelationId.</summary>
    public Guid Id { get; set; }
    /// <summary>The buyer; Payments charges this customer's wallet.</summary>
    public string CustomerId { get; set; } = "";
    /// <summary>Total in the smallest currency unit (whole Toman). A long, never a double: money must be exact.</summary>
    public long Amount { get; set; }
    /// <summary>Currency code. "IRT" = Iranian Toman, the demo currency.</summary>
    public string Currency { get; set; } = "IRT";
    /// <summary>Customer-facing state; only the saga changes it after creation.</summary>
    public OrderState State { get; set; }
    /// <summary>Human-readable reason for a rejection / compensation (e.g. "insufficient funds").</summary>
    public string? FailureReason { get; set; }
    /// <summary>When the API accepted the order (UTC, so all services agree regardless of time zone).</summary>
    public DateTime CreatedAtUtc { get; set; }
    /// <summary>When the order was last changed by the saga.</summary>
    public DateTime UpdatedAtUtc { get; set; }
    /// <summary>Client-supplied key; a second POST with the same key returns the same order (S14).</summary>
    public string IdempotencyKey { get; set; } = "";
    /// <summary>Scenario Lab experiment this order belongs to, or null for a normal storefront order.</summary>
    public Guid? ScenarioId { get; set; }
    /// <summary>The order lines. "[]" is a C# 12 collection expression: start with an empty list.</summary>
    public List<OrderItem> Items { get; set; } = [];
}

/// <summary>
/// One line of an order. Name and price are SNAPSHOTS copied at checkout: if the catalog changes later,
/// the order still shows what the customer actually bought and paid.
/// </summary>
public sealed class OrderItem
{
    /// <summary>Auto-increment primary key (lines have no meaning outside their order).</summary>
    public long Id { get; set; }
    /// <summary>Foreign key to <see cref="Order.Id"/>.</summary>
    public Guid OrderId { get; set; }
    /// <summary>The product id as known by Inventory. Not a foreign key: the catalog lives in another database.</summary>
    public Guid ProductId { get; set; }
    /// <summary>Product name at checkout time.</summary>
    public string ProductNameSnapshot { get; set; } = "";
    /// <summary>Unit price at checkout time (whole Toman).</summary>
    public long UnitPriceSnapshot { get; set; }
    /// <summary>How many units were ordered (validated &gt; 0 by the API).</summary>
    public int Quantity { get; set; }
}

/// <summary>Append-only history of every order / saga transition (what the customer and the developer console read).</summary>
/// <remarks>
/// Written in the SAME transaction as the transition itself, so the audit can never disagree with the
/// state. Rows are only ever inserted, never updated or deleted (except by the demo reset).
/// </remarks>
public sealed class OrderAudit
{
    /// <summary>Auto-increment key; ordering by it gives the exact commit order of the transitions.</summary>
    public long Id { get; set; }
    /// <summary>The order this line belongs to (indexed for the per-order diagnostics view).</summary>
    public Guid OrderId { get; set; }
    /// <summary>What caused the transition: a message type, or "Timeout" / "Api" / "ManualRetry".</summary>
    public string Trigger { get; set; } = "";      // message type or "Timeout" / "Api"
    /// <summary>Order state before the transition (null for the very first line).</summary>
    public string? OrderFrom { get; set; }
    /// <summary>Order state after the transition.</summary>
    public string? OrderTo { get; set; }
    /// <summary>Saga state before the transition (null for the very first line).</summary>
    public string? SagaFrom { get; set; }
    /// <summary>Saga state after the transition.</summary>
    public string? SagaTo { get; set; }
    /// <summary>Plain-language explanation from the saga decision (e.g. "stock reserved → asking Payments ...").</summary>
    public string Detail { get; set; } = "";
    /// <summary>When the transition happened (UTC).</summary>
    public DateTime AtUtc { get; set; }
}
