// ==================================================================================================
// MiniShop.Orders — Data/OrdersDbContext.cs
// ==================================================================================================
//
// WHAT THIS FILE IS
//   The EF Core DbContext for orders.db: it lists the tables of the Orders service and configures keys,
//   indexes and conversions.
//
// WHERE IT SITS IN THE ARCHITECTURE
//   "Database per service": orders.db belongs to Orders alone. Inventory and Payments have their own
//   files and never read this one. Because the business tables (Orders, SagaInstances, OrderAudit) AND
//   the pattern tables (Outbox, Inbox) live in the SAME database, one local transaction can update all
//   of them atomically. That single fact is what makes the Transactional Outbox and the Inbox work.
//
// PATTERNS
//   - IOutboxDbContext (shared/Outbox) : this context has an Outbox table → PublishViaOutbox / SendViaOutbox
//                                        and the OutboxDispatcher work with it.
//   - IInboxDbContext  (shared/Inbox)  : this context has an Inbox table → IdempotentConsumer can
//                                        de-duplicate incoming messages (S06 duplicate delivery).
//
// Read next: Saga/OrderSagaState.cs (the saga row and its concurrency token).
// ==================================================================================================

// EF Core base classes (DbContext, DbSet, ModelBuilder).
using Microsoft.EntityFrameworkCore;
// Order, OrderItem, OrderAudit.
using MiniShop.Orders.Domain;
// OrderSagaState.
using MiniShop.Orders.Saga;
// InboxMessage + IInboxDbContext.
using MiniShop.Shared.Inbox;
// OutboxMessage + IOutboxDbContext.
using MiniShop.Shared.Outbox;

namespace MiniShop.Orders.Data;

/// <summary>orders.db — owned exclusively by the Orders service. No other service opens this file.</summary>
/// <param name="options">
/// Connection settings (SQLite file path, interceptors) built in Program.cs and injected by DI.
/// The class uses a C# 12 primary constructor: the parameter is passed straight to the base DbContext.
/// </param>
public sealed class OrdersDbContext(DbContextOptions<OrdersDbContext> options) : DbContext(options), IOutboxDbContext, IInboxDbContext
{
    /// <summary>The Order aggregates (table "Orders").</summary>
    public DbSet<Order> Orders => Set<Order>();
    /// <summary>The order lines (table "OrderItems").</summary>
    public DbSet<OrderItem> OrderItems => Set<OrderItem>();
    /// <summary>One persisted saga instance per order (table "SagaInstances").</summary>
    public DbSet<OrderSagaState> SagaInstances => Set<OrderSagaState>();
    /// <summary>Append-only audit of every transition (table "OrderAudit").</summary>
    public DbSet<OrderAudit> OrderAudit => Set<OrderAudit>();
    /// <summary>Transactional Outbox: messages waiting to be published to RabbitMQ.</summary>
    public DbSet<OutboxMessage> Outbox => Set<OutboxMessage>();
    /// <summary>Inbox: MessageIds already processed, used to ignore duplicate deliveries.</summary>
    public DbSet<InboxMessage> Inbox => Set<InboxMessage>();

    /// <summary>Configures keys, indexes and conversions with the fluent API (no attributes on the domain classes).</summary>
    /// <param name="b">EF Core's model builder.</param>
    protected override void OnModelCreating(ModelBuilder b)
    {
        b.Entity<Order>(e =>
        {
            // The Guid generated by the API is the primary key.
            e.HasKey(o => o.Id);
            // The UNIQUE index is the real guarantee behind S14: even if two identical requests race past
            // the "does it exist?" check, the database refuses the second INSERT.
            e.HasIndex(o => o.IdempotencyKey).IsUnique();   // S14: one order per Idempotency-Key
            // Store the enum as text ("Confirmed") instead of a number (4): readable rows, and reordering
            // the enum later cannot silently change the meaning of stored data.
            e.Property(o => o.State).HasConversion<string>();
            // One order has many items; OrderItem.OrderId is the foreign key. WithOne() without a lambda
            // because OrderItem has no navigation back to Order.
            e.HasMany(o => o.Items).WithOne().HasForeignKey(i => i.OrderId);
        });
        b.Entity<OrderSagaState>(e =>
        {
            // CorrelationId (= OrderId) is the key: exactly one saga per order.
            e.HasKey(s => s.CorrelationId);
            // Optimistic concurrency: EF adds "WHERE Version = <value I read>" to every UPDATE. If another
            // writer changed the row in the meantime, 0 rows match and EF throws
            // DbUpdateConcurrencyException instead of silently overwriting the other decision.
            e.Property(s => s.Version).IsConcurrencyToken();
            // The timeout worker queries "DeadlineUtc <= now" every second; the index keeps that cheap.
            e.HasIndex(s => s.DeadlineUtc);
        });
        // The diagnostics view loads the audit of one order; index it by OrderId.
        b.Entity<OrderAudit>(e => e.HasIndex(a => a.OrderId));
        b.Entity<OutboxMessage>(e =>
        {
            // The dispatcher looks for rows where PublishedAtUtc is null (= still pending).
            e.HasIndex(m => m.PublishedAtUtc);
            // Diagnostics filter the outbox by order.
            e.HasIndex(m => m.CorrelationId);
        });
        b.Entity<InboxMessage>(e =>
        {
            // MessageId is the key: inserting the same MessageId twice is impossible, which is the whole
            // point of the Inbox (a duplicate delivery is detected and ignored, S06).
            e.HasKey(m => m.MessageId);
            // Diagnostics filter the inbox by order.
            e.HasIndex(m => m.CorrelationId);
        });
    }
}
